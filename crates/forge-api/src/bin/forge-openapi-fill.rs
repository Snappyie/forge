//! Generates OpenAPI path entries for every route the router serves.
//!
//! Run with `cargo run --bin forge-openapi-fill > missing.json`, then paste
//! the result into `openapi.rs::paths()`. The drift tests in that module fail
//! until every served route is described, so the document cannot silently fall
//! behind the router again.
//!
//! This is a development aid, not a runtime component: it reads `router.rs` to
//! recover the path and method list, and emits starter entries that a human
//! then annotates with summaries and schemas.

use std::collections::BTreeMap;

fn main() {
    let source = include_str!("../../src/router.rs");
    let served = extract(source);

    // Paths already described by hand in openapi.rs.
    let existing = std::fs::read_to_string("src/openapi.rs").unwrap_or_default();
    let documented: Vec<&str> = existing
        .lines()
        .filter_map(|line| line.trim().strip_prefix('"'))
        .filter_map(|line| line.split('"').next())
        .filter(|candidate| candidate.starts_with('/'))
        .collect();

    let mut missing: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for (method, path) in &served {
        if documented.contains(&path.as_str()) {
            continue;
        }
        missing.entry(path).or_default().push(method);
    }

    eprintln!(
        "{} routes served, {} documented, {} paths missing",
        served.len(),
        documented.len(),
        missing.len()
    );

    println!("// Generated by `cargo run --bin forge-openapi-fill`.");
    println!("// Annotate each summary and schema; the drift tests will hold them here.");
    for (path, methods) in missing {
        println!();
        println!("        paths.insert(");
        println!("            {path:?}.into(),");
        println!("            json!({{");
        for method in methods {
            println!(
                "                {method:?}: op(\n                    \"TODO: describe this endpoint\",\n                    \"TODO\",\n                    \"todo_{}\",\n                    None,\n                    vec![],\n                    None,\n                    \"200\",\n                ),",
                method
            );
        }
        println!("            }}),");
        println!("        );");
    }
}

/// Recovers `(method, path)` pairs from the router source.
///
/// Route paths appear as `format!("{PREFIX}/thing")`, sometimes split across
/// lines, so the macro call is the anchor rather than a bare `{PREFIX}` mention.
/// The methods follow the closing paren of that call.
fn extract(source: &str) -> Vec<(String, String)> {
    let mut out = Vec::new();
    let mut cursor = 0usize;

    while let Some(offset) = source[cursor..].find("format!(") {
        let after = &source[cursor + offset + "format!(".len()..];
        cursor += offset + "format!(".len();

        // Only a bare `format!(` immediately followed by a quote is a path.
        let trimmed = after.trim_start();
        if !trimmed.starts_with('"') {
            continue;
        }
        let quoted = &trimmed[1..];
        let Some(end_quote) = quoted.find('"') else {
            continue;
        };
        let literal = &quoted[..end_quote];
        let Some(path) = literal.strip_prefix("{PREFIX}") else {
            continue;
        };
        let path = path.trim().to_string();

        // Methods are named in the chain that follows, until the next route.
        let tail = &quoted[end_quote..];
        let window_end = tail.find(".route(").unwrap_or(tail.len().min(400));
        let window = &tail[..window_end];
        for method in ["get", "post", "put", "patch", "delete"] {
            // `crate::x::handler` preceded by the bare method name, not part of
            // a longer identifier.
            let needle = format!("{method}(");
            let mut from = 0usize;
            while let Some(at) = window[from..].find(&needle) {
                let before = window[..from + at].chars().next_back();
                let is_call = before
                    .map(|c| c.is_whitespace() || c == ':' || c == '.')
                    .unwrap_or(false);
                if is_call {
                    out.push((method.to_string(), path.clone()));
                    break;
                }
                from += at + needle.len();
            }
        }
    }

    out.sort();
    out.dedup();
    out
}
