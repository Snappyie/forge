#!/usr/bin/env node
/*
 * Splits the dynamic routes so the console can be statically exported.
 *
 * `output: "export"` requires every dynamic route to have
 * `generateStaticParams`, but Next refuses to let a `"use client"` component
 * export it:
 *
 *     Page "/executions/[id]/page" cannot use both "use client" and export
 *     function "generateStaticParams()".
 *
 * The id is a UUID, so enumerating real values is impossible - and pointless,
 * because the view fetches the entity from the API on the client and only needs
 * the param to do so.
 *
 * So each `[id]/page.tsx` is split in two:
 *
 *   - `[id]/view.tsx`  the existing client component, unchanged apart from taking
 *                      the id as a prop instead of from `params`
 *   - `[id]/page.tsx`  a server component that supplies the single exported
 *                      param set and hands it down
 *
 * The build emits one HTML shell per route, and the Rust server falls back to it
 * for any unmatched path, so a pasted deep link still works.
 *
 * Idempotent: a route already carrying the wrapper marker is left alone.
 *
 * The rewrites are line-oriented rather than one large pattern, because a nested
 * TypeScript prop signature is not reliably matchable as a regex and the exact
 * indentation has changed with tooling more than once.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// `.mjs` is ESM, so there is no `__dirname`.
const HERE = path.dirname(fileURLToPath(import.meta.url));
const APP_DIR = path.join(HERE, "..", "src", "app");

const MARKER = "static export wrapper";

/** The dynamic routes and their default-exported component names. */
const ROUTES = [
  { dir: "executions", component: "ExecutionDetailPage" },
  { dir: "jobs", component: "JobDetailPage" },
  { dir: "workers", component: "WorkerDetailPage" },
  { dir: "incidents", component: "IncidentDetailPage" },
  { dir: "workflows", component: "WorkflowDetailPage" },
];

/**
 * Locates the component declaration and the line that closes its parameter
 * list, which is the first `}) {` at column 0 after it starts.
 */
function findSignature(lines, component) {
  const start = lines.findIndex((line) =>
    line.startsWith(`export default function ${component}(`)
  );
  if (start === -1) return null;

  for (let i = start + 1; i < lines.length; i += 1) {
    if (lines[i] === "}) {") return { start, end: i };
  }
  return null;
}

const WRAPPER = `/**
 * Server component wrapper for the ${MARKER}.
 *
 * The client component cannot export \`generateStaticParams\`, so the param set is
 * declared here and passed down. \`EXPORT_ID\` is a placeholder: the real id arrives
 * from the URL at runtime, and the exported HTML is a shell that the client router
 * re-resolves for whatever the URL actually contains.
 *
 * Generated by \`scripts/split-dynamic-routes.mjs\` - do not edit by hand.
 */
import { EXPORT_ID } from "@/lib/export-params";
import View from "./view";

export function generateStaticParams() {
  return [{ id: EXPORT_ID }];
}

export default function Page() {
  return <View id={EXPORT_ID} />;
}
`;

let changed = 0;
let skipped = 0;

for (const route of ROUTES) {
  const dir = path.join(APP_DIR, route.dir, "[id]");
  const pagePath = path.join(dir, "page.tsx");
  const viewPath = path.join(dir, "view.tsx");

  if (!fs.existsSync(pagePath)) {
    console.error(`missing ${path.relative(HERE, pagePath)}`);
    skipped += 1;
    continue;
  }

  const source = fs.readFileSync(pagePath, "utf8");
  if (source.includes(MARKER)) {
    console.log(`already split: ${route.dir}/[id]`);
    skipped += 1;
    continue;
  }

  const lines = source.split("\n");
  const signature = findSignature(lines, route.component);
  if (!signature) {
    console.error(`could not find the signature of ${route.component}`);
    skipped += 1;
    continue;
  }

  // 1. The view takes the id as a prop rather than reading it from `params`.
  lines.splice(
    signature.start,
    signature.end - signature.start + 1,
    `export default function ${route.component}({ id }: { id: string }) {`
  );

  // 2. `use(params)` is no longer where the id comes from.
  const useIndex = lines.findIndex((line) => line.includes("use(params)"));
  if (useIndex === -1) {
    console.error(`could not find 'use(params)' in ${route.dir}/[id]`);
    skipped += 1;
    continue;
  }
  lines[useIndex] =
    "  // The id arrives as a prop from the server wrapper; see page.tsx.";

  fs.writeFileSync(viewPath, lines.join("\n"));
  fs.writeFileSync(pagePath, WRAPPER);
  changed += 1;
  console.log(`split: ${route.dir}/[id] -> view.tsx + page.tsx`);
}

console.log(`\n${changed} route(s) split, ${skipped} left alone`);